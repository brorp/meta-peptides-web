-- Usage life (days) captured when the order is created, so later product edits
-- do not move old reorder reminders. NULL means it was not captured.
ALTER TABLE order_items
ADD COLUMN IF NOT EXISTS usage_days_at_purchase integer;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'order_items_usage_days_nonnegative'
  ) THEN
    ALTER TABLE order_items
    ADD CONSTRAINT order_items_usage_days_nonnegative
    CHECK (usage_days_at_purchase IS NULL OR usage_days_at_purchase >= 0);
  END IF;
END $$;

