// Regenerates the command reference in README.md from COMMAND_SPECS, so the
// onboarding doc always matches !help. Run after changing a command:
//   npm run docs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COMMAND_SPECS } from "./commands.mjs";
import { buildTemplate } from "./help.mjs";

export const DOCS_START = "<!-- COMMANDS:START (generated by `npm run docs`, do not edit by hand) -->";
export const DOCS_END = "<!-- COMMANDS:END -->";

export function renderCommandDocs() {
  const out = [];
  for (const [name, spec] of Object.entries(COMMAND_SPECS)) {
    if (name === "!help") continue;
    out.push(`### \`${name}\`${spec.directorsOnly ? " 🔒 direksi" : ""}`, "", `${spec.summary}.`, "");
    if (spec.argument) out.push(`Setelah nama command: ${spec.argument}.`, "");
    out.push("```text", buildTemplate(spec), "```", "");
    if (spec.fields?.length) {
      out.push("| Field | Wajib | Isi |", "| --- | --- | --- |");
      for (const field of spec.fields) {
        out.push(`| \`${field.name}\` | ${field.required ? "**ya**" : "-"} | ${field.description.replace(/\|/g, "\\|")} |`);
      }
      out.push("");
    }
    for (const note of spec.notes || []) out.push(`- ${note}`);
    if (spec.notes?.length) out.push("");
  }
  return out.join("\n").trim();
}

export function syncReadme(readme) {
  const start = readme.indexOf(DOCS_START);
  const end = readme.indexOf(DOCS_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md is missing the COMMANDS:START / COMMANDS:END markers");
  }
  return `${readme.slice(0, start + DOCS_START.length)}\n\n${renderCommandDocs()}\n\n${readme.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const readmeUrl = new URL("./README.md", import.meta.url);
  writeFileSync(readmeUrl, syncReadme(readFileSync(readmeUrl, "utf8")));
  console.log("README.md command reference updated.");
}
