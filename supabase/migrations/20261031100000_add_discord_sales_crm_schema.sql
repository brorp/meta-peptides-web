-- Discord sales CRM: leads pipeline, invoice/payment tracking, reimbursable
-- expenses, and product type (mainproduct vs misc).
--
-- Enums are strict so bot input cannot create values that the reporting
-- commands do not understand.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'lead_status_enum') THEN
    CREATE TYPE lead_status_enum AS ENUM ('hot', 'warm', 'cold', 'skip');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'lead_origin_enum') THEN
    CREATE TYPE lead_origin_enum AS ENUM (
      'ads',
      'tokopedia',
      'instagram',
      'threads',
      'tiktok',
      'fnf',
      'shopee',
      'website'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'lead_rejection_enum') THEN
    CREATE TYPE lead_rejection_enum AS ENUM (
      'harga',
      'company',
      'cara_penggunaan',
      'perizinan',
      'produk_tidak_ada',
      'ghosting'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'expense_paid_by_enum') THEN
    CREATE TYPE expense_paid_by_enum AS ENUM ('kas', 'rudi', 'rp');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'product_type_enum') THEN
    CREATE TYPE product_type_enum AS ENUM ('mainproduct', 'misc');
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS leads (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  whatsapp_phone text NOT NULL,
  full_name text NOT NULL,
  origin lead_origin_enum NOT NULL,
  status lead_status_enum NOT NULL DEFAULT 'warm',
  interest_product_id uuid REFERENCES products(id) ON DELETE SET NULL,
  interest_text text,
  rejection lead_rejection_enum,
  chat_date date NOT NULL,
  is_customer boolean NOT NULL DEFAULT false,
  notes text,
  domicile text,
  goal text,
  customer_id uuid REFERENCES customers(id) ON DELETE SET NULL,
  converted_at timestamptz,
  discord_user_id text,
  discord_username text,
  source_message_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT leads_whatsapp_phone_not_blank CHECK (btrim(whatsapp_phone) <> ''),
  CONSTRAINT leads_full_name_not_blank CHECK (btrim(full_name) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS leads_whatsapp_phone_unique_idx
ON leads (whatsapp_phone);

CREATE UNIQUE INDEX IF NOT EXISTS leads_source_message_id_unique_idx
ON leads (source_message_id)
WHERE source_message_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_leads_chat_date
ON leads (chat_date);

CREATE INDEX IF NOT EXISTS idx_leads_followup
ON leads (is_customer, chat_date, status);

CREATE INDEX IF NOT EXISTS idx_leads_origin
ON leads (origin);

-- No anon/authenticated policy is created. Leads are only reachable through
-- server routes that use the Supabase service role.
ALTER TABLE leads ENABLE ROW LEVEL SECURITY;

